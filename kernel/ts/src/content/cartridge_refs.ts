// Shared diagnostic helpers for the loader stages (content/cartridge.ts;
// protocol/cartridge.schema.json DiagnosticCode). Semantic checks are the compiler's (lib/loka/content).
import { encode } from '../foundation/canonical.ts';
import type { Diagnostic, DiagnosticCode, TextKey } from '../contracts.gen.ts';

export type Data = Record<string, string | number>;
export type Obj = { [key: string]: any };

export const isObj = (v: unknown): v is Obj =>
  typeof v === 'object' && v !== null && !Array.isArray(v);

export const diag = (
  code: DiagnosticCode,
  path: string,
  data: Data = {},
  suggested: string[] = [],
): Diagnostic => ({
  severity: 'error',
  code,
  path,
  message_key: `diagnostics.${code.toLowerCase()}` as TextKey,
  data,
  suggested_capabilities: suggested,
});

// A member step in the loader path grammar (DiagnosticCode, Diagnostic.path).
export const step = (name: string) =>
  /^[a-z0-9_]+$/.test(name) ? `.${name}` : `[${encode(name)}]`;
