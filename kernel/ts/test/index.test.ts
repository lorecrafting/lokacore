// The generated area index (docs/system/cartridge.md#content-reports; design section 6): `bin/loka
// index` writes `areas/INDEX.md` and one `areas/<area>/INDEX.md` from a real compile. The planted
// cartridge is the design's worked example shrunk to three areas and one shared item, so every byte
// below is hand-written from the format rules and never read back from the generator. Breaks are
// named per test.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import {
  chmodSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { after, test } from 'node:test';
import { compiled } from '../play/compiled.ts';
import { indexes, writeIndexes } from '../play/index.ts';

const tmp = mkdtempSync(join(tmpdir(), 'loka-index-'));
after(() => rmSync(tmp, { recursive: true, force: true }));
const root = resolve(import.meta.dirname, '../../..');

const ref = (key: string) => ({
  cartridge_id: 'area_fixture',
  cartridge_version: '0.0.1',
  kind: 'room',
  key,
});
const room = (name: string, exits: Record<string, string>, extra: object = {}) => ({
  name: { prose: name },
  description: { prose: `${name} here.` },
  exits: Object.fromEntries(Object.entries(exits).map(([dir, to]) => [dir, { to }])),
  ...extra,
});
const item = (keywords: string[], location: object) => ({
  keywords,
  name: { prose: keywords[0] },
  room_line: { prose: `A [${keywords[0]}](${keywords[0]}) lies here.` },
  description: { prose: 'Thing.' },
  location,
});

/** Writes the tree a `{rel: value}` map names; a value is JSON, or a string written as is. */
function tree(dir: string, at: Record<string, unknown>) {
  for (const [rel, value] of Object.entries(at)) {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), typeof value === 'string' ? value : JSON.stringify(value));
  }
  return dir;
}

// Three areas: hollow (a folder, two rooms), edge (a folder, one room) and deep (a bundle, no room
// file of its own). `rope` is named by an item of hollow and one of edge, so it belongs at the root.
const FIXTURE = {
  'cartridge.json': {
    api_version: 'loka/v3',
    id: 'area_fixture',
    version: '0.0.1',
    title: 'Area Fixture',
    requires: {
      kernel_api: { at_least: '1.0', below: '2.0' },
      content_schema: 1,
      rule_ir: 1,
      capabilities: { movement: 1, containment: 1, schedule: 1, alternates: 1, knowledge: 1 },
      client_features: [],
    },
    supported_profiles: ['offline_private'],
    entry: ref('awakening_clearing'),
  },
  'areas/hollow/rooms/awakening_clearing.json': room('Clearing', { north: 'high_terrace' }),
  // Its lock names a room of another area: a crossing, but not a border (it has no direction).
  'areas/hollow/rooms/high_terrace.json': room(
    'High terrace',
    { north: 'thinning', south: 'awakening_clearing' },
    {
      locks: { enter: { op: 'visited_count', room: 'thinning', at_least: 1 } },
    },
  ),
  'areas/edge/rooms/thinning.json': room('Thinning', { south: 'high_terrace' }),
  'areas/deep.json': { rooms: { well: room('Well', {}) } },
  // Maren walks out of her area in the day: a room named across a border, from a non-room.
  'areas/hollow/npcs/maren.json': {
    keywords: ['maren'],
    name: { prose: 'Maren' },
    room_line: { prose: 'A [maren](maren) stands here.' },
    description: { prose: 'Tall.' },
    room: 'high_terrace',
    daily_schedule: { 9: 'thinning' },
  },
  'areas/hollow/items/cloak.json': item(['cloak'], { in: 'item', item: 'rope' }),
  'areas/edge/items/boots.json': item(['boots'], { in: 'item', item: 'rope' }),
  // A holder: two areas' items start inside it, so it belongs at the root.
  'items/rope.json': { ...item(['rope'], { in: 'room', room: 'thinning' }), container: true },
};
const source = tree(join(tmp, 'area_fixture'), FIXTURE);
const dev = compiled(source);
if (typeof dev === 'string') throw new Error(`the fixture does not compile: ${dev}`);
const pages = indexes(source, dev)!;

// Break: the owner's three header lines become one, drop the generator naming or the guide link.
test('every index opens with the three header lines the owner asked for', () => {
  const header = (up: string) => [
    'Generated by bin/loka index; do not edit: bin/regen.sh rewrites it.',
    `An area folder's rules: [Cartridge layout](${up}docs/BUILDERS-GUIDE.md#cartridge-layout).`,
  ];
  // `areas/INDEX.md` sits three folders below the cartridge root, `areas/<area>/INDEX.md` four.
  assert.deepEqual(pages['areas/INDEX.md']!.split('\n').slice(0, 3), [
    '# The areas of area_fixture',
    ...header('../../../'),
  ]);
  assert.deepEqual(pages['areas/hollow/INDEX.md']!.split('\n').slice(0, 3), [
    '# The area hollow of area_fixture',
    ...header('../../../../'),
  ]);
});

// Break: the borders list a root room as `(root)/<key>`; a transport or a schedule is listed as an
// exit; the direction is dropped; the root row is left out of the table.
test('the root index counts each area, and lists a border as area --room direction--> area/room', () => {
  assert.equal(
    pages['areas/INDEX.md'],
    [
      '# The areas of area_fixture',
      'Generated by bin/loka index; do not edit: bin/regen.sh rewrites it.',
      "An area folder's rules: [Cartridge layout](../../../docs/BUILDERS-GUIDE.md#cartridge-layout).",
      '',
      '| area                      | rooms | npcs | items | quests | dialogues | reactions | other |',
      '| ------------------------- | ----- | ---- | ----- | ------ | --------- | --------- | ----- |',
      '| [deep](deep/INDEX.md)     | 1     | 0    | 0     | 0      | 0         | 0         | 0     |',
      '| [edge](edge/INDEX.md)     | 1     | 0    | 1     | 0      | 0         | 0         | 0     |',
      '| [hollow](hollow/INDEX.md) | 2     | 1    | 1     | 0      | 0         | 0         | 0     |',
      '| (root)                    | 0     | 0    | 1     | 0      | 0         | 0         | 0     |',
      '',
      'Borders (exit or transport): edge --thinning south--> hollow/high_terrace; hollow --high_terrace north--> edge/thinning',
      'Entry: hollow/awakening_clearing',
      '',
      'Root definitions named by two or more areas: items/rope (edge, hollow)',
      '',
    ].join('\n'),
  );
});

// Break: a crossing is listed only one way (`->`), or the `<-` direction names the target instead
// of the root file that names the area's room.
test('an area index lists its rooms, then what crosses the border in both directions', () => {
  assert.equal(
    pages['areas/hollow/INDEX.md'],
    [
      '# The area hollow of area_fixture',
      'Generated by bin/loka index; do not edit: bin/regen.sh rewrites it.',
      "An area folder's rules: [Cartridge layout](../../../../docs/BUILDERS-GUIDE.md#cartridge-layout).",
      '',
      '## Rooms (2)',
      'awakening_clearing [entry]  exits: north high_terrace',
      'high_terrace  exits: north -> edge/thinning, south awakening_clearing',
      '',
      '## NPCs (1)',
      'maren @high_terrace  daily_schedule.9 -> edge/thinning',
      '',
      '## Items (1)',
      'cloak in items/rope',
      '',
      '## Crosses the border',
      "Names other areas' rooms: maren.daily_schedule.9 -> edge/thinning; high_terrace.exits.north.to -> edge/thinning; high_terrace.locks.enter.room -> edge/thinning",
      'Names the root: items/rope (cloak)',
      '',
    ].join('\n'),
  );
});

// Break: a bundle is not an area (no `areas/deep/` page and no folder made for it), so its
// definitions vanish from the table and its crossings are dropped.
test('a bundle-only area gets its folder and its own index', () => {
  assert.deepEqual(Object.keys(pages).sort(), [
    'areas/INDEX.md',
    'areas/deep/INDEX.md',
    'areas/edge/INDEX.md',
    'areas/hollow/INDEX.md',
  ]);
  // `edge` is named from the root (`items/rope` holds its room), `deep` from nothing.
  assert.match(pages['areas/edge/INDEX.md']!, /Named from the root: edge\/thinning <- items\/rope/);
  assert.match(pages['areas/deep/INDEX.md']!, /^## Rooms \(1\)\nwell {2}exits: none$/m);
});

// Break: a transport from the root to an area is not a border; a flat cartridge gets an empty
// index instead of none (a generated file nobody asked for, or a crash on the missing folder).
test('a transport into an area is a border, and a flat cartridge has no index', () => {
  const flat = join(tmp, 'fast_travel');
  cpSync(join(root, 'cartridges/fast_travel_sampler'), flat, { recursive: true });
  mkdirSync(join(flat, 'areas/south/rooms'), { recursive: true });
  cpSync(join(flat, 'rooms/south_post.json'), join(flat, 'areas/south/rooms/south_post.json'));
  rmSync(join(flat, 'rooms/south_post.json'));
  const travel = compiled(flat);
  if (typeof travel === 'string')
    throw new Error(`fast_travel_sampler does not compile: ${travel}`);
  const borders = /^Borders \(exit or transport\): (.*)$/m.exec(
    indexes(flat, travel)!['areas/INDEX.md']!,
  );
  assert.equal(
    borders?.[1],
    '(root) --lane south--> south/south_post; (root) --north_road--> south/south_post; ' +
      'south --south_post north--> rooms/lane; south --south_road--> rooms/north_post',
  );
  // Both of a transport's rooms in one area is no border: only the two room exits cross.
  const inside = join(tmp, 'fast_travel_inside');
  cpSync(join(root, 'cartridges/fast_travel_sampler'), inside, { recursive: true });
  mkdirSync(join(inside, 'areas/south/rooms'), { recursive: true });
  for (const key of ['north_post', 'south_post'])
    cpSync(join(inside, `rooms/${key}.json`), join(inside, `areas/south/rooms/${key}.json`));
  rmSync(join(inside, 'rooms/north_post.json'));
  rmSync(join(inside, 'rooms/south_post.json'));
  const inner = compiled(inside);
  if (typeof inner === 'string') throw new Error(`fast_travel_sampler does not compile: ${inner}`);
  assert.match(
    indexes(inside, inner)!['areas/INDEX.md']!,
    /^Borders \(exit or transport\): \(root\) --lane north--> south\/north_post; \(root\) --lane south--> south\/south_post; south --north_post south--> rooms\/lane; south --south_post north--> rooms\/lane$/m,
  );
  const flatDir = tree(join(tmp, 'flat'), {
    'cartridge.json': {
      ...(FIXTURE['cartridge.json'] as object),
      id: 'flat_fixture',
      entry: { ...ref('only'), cartridge_id: 'flat_fixture' },
    },
    'rooms/only.json': room('Only', {}),
  });
  const only = compiled(flatDir);
  if (typeof only === 'string') throw new Error(`the flat fixture does not compile: ${only}`);
  assert.equal(indexes(flatDir, only), null);
  assert.deepEqual(writeIndexes(flatDir, only), []);
  assert.equal(existsSync(join(flatDir, 'areas')), false);
});

// Break: writeIndexes does not make an area's folder, so a bundle-only area throws ENOENT.
test('writes every page it names, making the folder a bundle-only area lacks', () => {
  const dir = tree(join(tmp, 'written'), FIXTURE);
  assert.deepEqual(writeIndexes(dir, dev), Object.keys(pages));
  for (const rel of Object.keys(pages)) assert.equal(existsSync(join(dir, rel)), true, rel);
});

// Break: `bin/loka` has no `index` arm (the arguments fall through to the usage line), a flat
// cartridge exits non-zero instead of saying so, or a bad argument list is not a usage error.
test('bin/loka index writes the pages and says so for a cartridge with none', () => {
  // mise is stubbed as CI has none (as check.test.ts); mix comes from PATH.
  const bin = join(tmp, 'bin');
  mkdirSync(bin, { recursive: true });
  writeFileSync(join(bin, 'mise'), '#!/bin/sh\nshift 2\nexec "$@"\n');
  chmodSync(join(bin, 'mise'), 0o755);
  const env = { ...process.env, PATH: `${bin}:${process.env.PATH}` };
  const source = tree(join(tmp, 'cli'), FIXTURE);
  const index = (...args: string[]) =>
    spawnSync(join(root, 'bin/loka'), ['index', ...args], { encoding: 'utf8', env });
  const run = index(source);
  assert.equal(run.status, 0, run.stderr);
  assert.equal(
    run.stdout,
    ['areas/INDEX.md', 'areas/deep/INDEX.md', 'areas/edge/INDEX.md', 'areas/hollow/INDEX.md']
      .map((rel) => `${rel}\n`)
      .join(''),
  );
  assert.equal(index().status, 2); // usage
  assert.equal(index(source, 'extra').status, 2);
  const flat = tree(join(tmp, 'cli-flat'), {
    'cartridge.json': {
      ...(FIXTURE['cartridge.json'] as object),
      id: 'flat_fixture',
      entry: { ...ref('a'), cartridge_id: 'flat_fixture' },
    },
    'rooms/a.json': room('A', {}),
  });
  const none = index(flat);
  assert.equal(none.status, 0, none.stderr); // a flat cartridge is not an error
  assert.match(none.stderr, /no areas\/ folder/);
});
