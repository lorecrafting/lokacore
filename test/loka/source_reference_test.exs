defmodule Loka.SourceReferenceTest do
  use ExUnit.Case, async: true

  @moduletag :tmp_dir

  # The smallest schema set that reaches each rendering rule: a kind dispatch whose partial is
  # dropped, required and group-required fields, a nested object, a blank meaning, the scene link,
  # a shared type that is a string or an object.
  @defs %{
    "$defs" => %{
      "source.notes" => %{
        "if" => %{"required" => ["extends"]},
        "then" => %{"$ref" => "#/$defs/partial.Note"},
        "else" => %{"$ref" => "#/$defs/source.Note"}
      },
      "partial.Note" => %{"properties" => %{"only_partial" => %{"type" => "string"}}},
      "source.Note" => %{
        "description" => "One note.",
        "required" => ["title"],
        "allOf" => [%{"anyOf" => [%{"required" => ["a"]}, %{"required" => ["b"]}]}],
        "properties" => %{
          "title" => %{"$ref" => "#/$defs/Key", "description" => "Its a|b name."},
          "a" => %{"type" => "array", "items" => %{"type" => "string"}},
          "b" => %{"properties" => %{"c" => %{"enum" => ["x", "y"]}}, "type" => "object"},
          "d" => %{
            "anyOf" => [
              %{
                "description" => "Tagged.",
                "properties" => %{"k" => %{"const" => true}, "e" => %{"type" => "boolean"}}
              }
            ]
          },
          "ref" => %{"$ref" => "#/$defs/Ref"},
          "when" => %{"$ref" => "#/$defs/Policy"}
        }
      },
      "Key" => %{"type" => "string"},
      "Ref" => %{
        "anyOf" => [
          %{"type" => "string"},
          %{
            "type" => "object",
            "required" => ["id"],
            "properties" => %{"id" => %{"type" => "string", "description" => "The id."}}
          }
        ]
      },
      "source.scenes" => %{"properties" => %{}},
      "Step" => %{
        "anyOf" => [
          %{
            "description" => "Say it.",
            "properties" => %{"op" => %{"const" => "say"}, "text" => %{"type" => "string"}}
          }
        ]
      },
      "Policy" => %{
        "anyOf" => [%{"properties" => %{"op" => %{"const" => "all"}}, "description" => "All."}]
      },
      "DialogueChoice" => %{"properties" => %{"label" => %{"type" => "string"}}},
      "source.ReactionRule" => %{
        "properties" => %{
          "on" => %{
            "anyOf" => [%{"properties" => %{"event" => %{"const" => "rang"}}}]
          }
        }
      }
    }
  }

  @kinds """
  # Source kinds

  Generated by `bin/source_reference.py` from `schemas/source/`; do not edit. A meaning is its `description` in `protocol/*.schema.json`. Required covers a full entry: conditional requirements are not shown, and `abstract` and `extends` entries are in the [builder's guide](../BUILDERS-GUIDE.md). Which file holds a kind is in [source layout](../system/cartridge.md#source-layout); a definition in its own file takes its key from the file name, so `key` is not a field. A manifest needs `entry` once the source has rooms. The compiler names each capability a kind needs, to lock under `requires.capabilities`.

  ## notes

  One note.

  | Field | Type | Required | Meaning |
  |---|---|---|---|
  | a | list of string | one of a group |  |
  | b | object | one of a group |  |
  | b.c | `x` or `y` |  |  |
  | d | any |  |  |
  | d{k=true} | variant |  | Tagged. |
  | d{k=true}.e | boolean |  |  |
  | ref | [Ref](source-kinds.gen.md#ref) |  |  |
  | title | [Key](source-kinds.gen.md#key) | yes | Its a\\|b name. |
  | when | [Policy](vocabulary.gen.md#policy-leaves) |  | See the type. |

  ## scenes

  The format is in [Writing the game](../guides/writing-the-game.md).

  ## Shared types

  ### Key

  Type: string.

  ### Ref

  Type: string or object.

  | Field | Type | Required | Meaning |
  |---|---|---|---|
  | id | string | in this form | The id. |

  ## Fields without a meaning

  8 fields.

  - `choice: label`
  - `notes: a`
  - `notes: b`
  - `notes: b.c`
  - `notes: d`
  - `notes: d{k=true}.e`
  - `notes: ref`
  - `steps say: text`
  """

  @vocabulary """
  # Vocabulary

  Generated by `bin/source_reference.py` from `schemas/source/`; do not edit. A meaning is its `description` in `protocol/*.schema.json`. Required covers a full entry: conditional requirements are not shown, and `abstract` and `extends` entries are in the [builder's guide](../BUILDERS-GUIDE.md). Which file holds a kind is in [source layout](../system/cartridge.md#source-layout); a definition in its own file takes its key from the file name, so `key` is not a field. A manifest needs `entry` once the source has rooms. The compiler names each capability a kind needs, to lock under `requires.capabilities`.

  ## Steps

  ### `say`

  Say it.

  | Field | Type | Required | Meaning |
  |---|---|---|---|
  | text | string |  |  |

  ## Policy leaves

  ### `all`

  All.

  Type: any.

  ## Events

  ### `rang`

  Type: any.

  ## Scene step types

  The scene format is in [Writing the game](../guides/writing-the-game.md).

  ## Choice fields

  | Field | Type | Required | Meaning |
  |---|---|---|---|
  | label | string |  |  |
  """

  defp generate(args),
    do: System.cmd("python3", ["bin/source_reference.py" | args], stderr_to_stdout: true)

  setup %{tmp_dir: tmp} do
    schemas = Path.join(tmp, "schemas")
    File.mkdir_p!(schemas)
    File.write!(Path.join(schemas, "defs.schema.json"), JSON.encode!(@defs))

    for kind <- ~w(notes scenes) do
      ref = "defs.schema.json#/$defs/source.#{kind}"
      File.write!(Path.join(schemas, "#{kind}.schema.json"), JSON.encode!(%{"$ref" => ref}))
    end

    {:ok, schemas: schemas, out: Path.join(tmp, "out")}
  end

  test "a small schema renders to the literal pages", %{schemas: schemas, out: out} do
    assert {_, 0} = generate([schemas, out])
    assert File.read!(Path.join(out, "source-kinds.gen.md")) == @kinds
    assert File.read!(Path.join(out, "vocabulary.gen.md")) == @vocabulary
  end

  test "--check fails when a meaning changed and the pages were not regenerated", ctx do
    assert {_, 0} = generate([ctx.schemas, ctx.out])
    assert {_, 0} = generate(["--check", ctx.schemas, ctx.out])

    defs =
      put_in(@defs, ["$defs", "source.Note", "properties", "title", "description"], "Another.")

    File.write!(Path.join(ctx.schemas, "defs.schema.json"), JSON.encode!(defs))

    assert {message, 1} = generate(["--check", ctx.schemas, ctx.out])
    assert message =~ "source-kinds.gen.md is out of date"
  end

  # Breaks: a field's line not taken from the schema (own, else its type's), an example from a
  # non-sampler cartridge or from an area folder missed, or a sampler edit the check does not see.
  test "the field guide lists each field's description and a sampler example", ctx do
    tmp = Path.dirname(ctx.out)
    carts = Path.join(tmp, "cartridges")
    defs = put_in(@defs, ["$defs", "Ref", "description"], "A planted ref.")
    File.write!(Path.join(ctx.schemas, "defs.schema.json"), JSON.encode!(defs))

    for {file, body} <- [
          {"b_sampler/notes/n.json", %{"title" => "t"}},
          {"a_sampler/areas/v/notes/m.json", %{"a" => []}},
          {"other/notes/o.json", %{"ref" => "x"}}
        ] do
      File.mkdir_p!(Path.dirname(Path.join(carts, file)))
      File.write!(Path.join(carts, file), JSON.encode!(body))
    end

    assert {_, 0} = generate([ctx.schemas, ctx.out, carts])
    guide = File.read!(Path.join(tmp, "FIELD-GUIDE.gen.md"))

    assert guide =~
             "| title | Its a\\|b name. | [Key](reference/source-kinds.gen.md#key) | [cartridges/b_sampler/notes/n.json](../cartridges/b_sampler/notes/n.json) |\n"

    assert guide =~
             "| a |  | list of string | [cartridges/a_sampler/areas/v/notes/m.json](../cartridges/a_sampler/areas/v/notes/m.json) |\n"

    assert guide =~ "| ref | A planted ref. | [Ref](reference/source-kinds.gen.md#ref) |  |\n"

    File.write!(Path.join(carts, "b_sampler/notes/k.json"), JSON.encode!(%{"ref" => "y"}))
    assert {message, 1} = generate(["--check", ctx.schemas, ctx.out, carts])
    assert message =~ "FIELD-GUIDE.gen.md is out of date"
  end
end
