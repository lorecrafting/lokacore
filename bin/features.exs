# Generates docs/features.gen.md, the feature map (owner decision
# docs/decisions/owner-decision-r5-setup-2026-09-25.md): one row per capability of
# protocol/capability_registry.json. Derived here: kind (residency, portability), the release
# profile it is first required in (docs/spec/release-scope.json), the rule module
# kernel/ts/src/rules/<key>.ts, the example transcripts cartridges/*/transcripts/<key>.jsonl
# and cross-checked (a declared Elixir differential, ADR-074). Hand-written in
# docs/features.json: spec, contracts, extra modules, fixtures, invariants, implemented_in.
# A capability is implemented when its rule module exists; then every column is required.
# It fails on a missing required cell, a row for no capability, an implemented_in without a
# rule module, and a contract, invariant or path that does not exist. `--check` regenerates in
# memory and exits 1 if the committed file differs.
#
#   elixir bin/features.exs [--check]
root = Path.expand("..", __DIR__)

for f <- ~w(canonical.ex contracts/schema.ex contracts.ex),
    do: Code.require_file(f, Path.join(root, "lib/loka/core"))

read = &JSON.decode!(File.read!(Path.join(root, &1)))
registry = read.("protocol/capability_registry.json")
rows = read.("docs/features.json")
scope = Map.new(read.("docs/spec/release-scope.json")["capabilities"], &{&1["id"], &1})
invariants = MapSet.new(read.("protocol/invariants.json"), & &1["id"])
defs = Loka.Core.Contracts.defs()
exists? = &File.exists?(Path.join(root, &1))
pin = &"#{&1["key"]}@#{&1["version"]}"

derived = fn e ->
  rule = "kernel/ts/src/rules/#{e["key"]}.ts"

  transcripts =
    Path.wildcard(Path.join(root, "cartridges/*/transcripts/#{e["key"]}.jsonl"))
    |> Enum.map(&Path.relative_to(&1, root))

  %{
    "implemented" => exists?.(rule),
    "modules" => if(exists?.(rule), do: [rule], else: []),
    "transcripts" => transcripts,
    "owned" => Enum.flat_map(~w(commands events definitions policies), &(e[&1] || []))
  }
end

required = ~w(spec contracts fixtures invariants implemented_in)

problems =
  for(
    {key, _} <- rows,
    not Enum.any?(registry, &(&1["key"] == key)),
    do: "#{key}: no such capability"
  ) ++
    for e <- registry,
        row = rows[e["key"]] || %{},
        d = derived.(e),
        p <-
          [
            for(c <- required, d["implemented"], not is_map_key(row, c), do: "missing #{c}"),
            if(d["implemented"] and d["transcripts"] == [], do: ["missing transcript"], else: []),
            if(row["implemented_in"] && !d["implemented"],
              do: ["implemented_in without a rule module"],
              else: []
            ),
            for(c <- row["contracts"] || [], not is_map_key(defs, c), do: "no contract #{c}"),
            for(i <- row["invariants"] || [], i not in invariants, do: "no invariant #{i}"),
            for(
              f <- (row["fixtures"] || []) ++ (row["modules"] || []),
              not exists?.(f),
              do: "no file #{f}"
            )
          ]
          |> List.flatten(),
        do: "#{pin.(e)}: #{p}"

if problems != [] do
  Enum.each(problems, &IO.puts(:stderr, "docs/features.json: #{&1}"))
  System.halt(1)
end

cell = fn
  [] -> "none"
  nil -> "—"
  xs when is_list(xs) -> Enum.map_join(xs, ", ", &"`#{&1}`")
  x -> x
end

table =
  for e <- registry do
    row = rows[e["key"]] || %{}
    d = derived.(e)
    s = scope[pin.(e)]

    cross =
      if e["differential"],
        do: "differential `#{e["differential"]}`",
        else: "no: TypeScript only (ADR-074)"

    [
      pin.(e),
      "#{e["residency"]}, #{e["portability"]}",
      if(s, do: "#{s["first_required"]} on (#{s["phase"]})", else: "—"),
      row["implemented_in"] || if(d["implemented"], do: "—", else: "not yet"),
      row["spec"] || "—",
      cell.(Enum.uniq(d["owned"] ++ (row["contracts"] || []))),
      cell.(d["modules"] ++ (row["modules"] || [])),
      cell.(row["fixtures"]),
      cell.(row["invariants"]),
      cell.(d["transcripts"]),
      if(d["implemented"], do: cross, else: "—")
    ]
    |> Enum.join(" | ")
    |> then(&"| #{&1} |")
  end

md =
  Enum.join(
    [
      "# Feature map (generated)",
      "",
      "Generated by `elixir bin/features.exs` from `protocol/capability_registry.json`,",
      "`docs/spec/release-scope.json` and [features.json](features.json). Do not edit. A capability",
      "is implemented when its rule module `kernel/ts/src/rules/<key>.ts` exists; its columns are",
      "then required. Available in: the first release profile that needs it, and every later one.",
      "Example transcripts replay in `kernel/ts/test/transcripts.test.ts`.",
      "",
      "| Capability | Kind | Available in | Implemented in | Spec | Contracts | TypeScript | Fixtures | Invariants | Example transcript | Cross-checked |",
      "|---|---|---|---|---|---|---|---|---|---|---|"
      | table
    ] ++ [""],
    "\n"
  )

target = Path.join(root, "docs/features.gen.md")

case System.argv() do
  [] ->
    File.write!(target, md)

  ["--check"] ->
    if File.read(target) != {:ok, md} do
      IO.puts(:stderr, "docs/features.gen.md is out of date: run elixir bin/features.exs")
      System.halt(1)
    end
end
