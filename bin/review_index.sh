#!/bin/sh
# Generates docs/reviews/README.md: the fixed header below plus one line per record, newest
# first: the record's first line (its title) and the last verdict word in it (the final round). A both-sides
# conflict on README.md is resolved by rerunning this. bin/check_docs.exs runs --check.
#   bin/review_index.sh [--check]   (--check: exit 1 if README.md is not the generated text)
set -eu
cd "$(dirname "$0")/.."
gen() {
  cat <<'HEAD'
# Independent reviews

Each record is written by a fresh agent that authored none of the reviewed work (AGENTS.md),
named `<YYYY-MM-DD>-<slice>-review.md`; findings, dispositions and fix rounds are in the record.
This file is generated by `bin/review_index.sh` (title and final verdict of each record, newest
first); never edit it by hand, rerun the script, also to resolve a merge conflict here. Records
of closed work are deleted once their lesson is folded, and linked by permalink
([move forward](../decisions/owner-decision-move-forward-2026-10-07.md)); older index lines are in
[this index at `15c7d41b`](https://github.com/lorecrafting/lokacore/blob/15c7d41be6c54208cd37b03aa87420f9f4b90d8e/docs/reviews/README.md).
Reviews before R2 live in the [legacy repository](https://github.com/lorecrafting/lokacore-v2-legacy)
(commit `997a7a8`, `docs/rewrite-v3/reviews/`).

HEAD
  for f in $(ls docs/reviews | grep -v '^README\.md$' | sort -r); do
    title=$(head -1 "docs/reviews/$f" | sed 's/^#* *//')
    # ponytail: the last verdict word anywhere wins; quote verdicts in findings in lower case, end a
    # record with its final verdict. Upgrade to a Verdict: field if mislabels recur.
    verdict=$(grep -oE 'APPROVE WITH NOTES|CHANGES REQUIRED|PASS WITH NOTES|APPROVE|PASS' "docs/reviews/$f" | tail -1 || true)
    echo "- [$title]($f)${verdict:+: **$verdict**}"
  done
}
if [ "${1-}" = --check ]; then
  gen | cmp -s - docs/reviews/README.md || { echo "docs/reviews/README.md is stale: run bin/review_index.sh"; exit 1; }
else
  gen > docs/reviews/README.md
fi
