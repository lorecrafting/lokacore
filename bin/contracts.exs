# Generates from protocol/ (spec 04 §12, 14 Gate R3, 05 §6):
# - kernel/ts/src/contracts.gen.ts: TypeScript types and flattened schemas of
#   protocol/*.schema.json, the evaluation-fault codes of protocol/error_registry.json, the
#   composition-profile limits, the artifact byte cap (ArtifactSize) and the command and
#   policy-op owners of protocol/capability_registry.json;
# - kernel/ts/test/subset.gen.ts: the same for the test-only probe
#   protocol/fixtures/subset.schema.json;
# - docs/contracts.gen.md (capability and schema docs) and docs/residency.gen.json (the
#   capability/residency matrix).
# It first fails on an Elixir host adapter without a differential (ADR-074). `--check`
# regenerates in memory and exits 1 if a committed file differs; `--check REGISTRY` reads a
# capability registry copy instead (the red control plants one). A schema outside the
# subset fails here as it fails `mix compile`.
#
#   elixir bin/contracts.exs [--check [REGISTRY]]
root = Path.expand("..", __DIR__)

for f <- ~w(canonical.ex contracts/schema.ex contracts.ex),
    do: Code.require_file(f, Path.join(root, "lib/loka/core"))

# ---- TypeScript rendering ----

defmodule Gen do
  alias Loka.Core.Canonical

  # The schemas are embedded as JSON.parse of a JSON string: in an object literal a
  # "__proto__" key would set the prototype instead of defining a property.
  @spec ts(%{String.t() => map()}, String.t()) :: String.t()
  def ts(defs, from) do
    names = defs |> Map.keys() |> Enum.sort()

    Enum.join(
      List.flatten([
        "// Generated by `elixir bin/contracts.exs` from #{from}. Do not edit.",
        Enum.map(names, &decl(&1, defs[&1])),
        "",
        "export type Contract = #{Enum.map_join(names, " | ", &lit/1)};",
        "",
        "export const DEFS: Readonly<Record<Contract, unknown>> = {",
        Enum.map(names, &"  #{lit(&1)}: JSON.parse(#{lit(lit(defs[&1]))}),"),
        "};",
        ""
      ]),
      "\n"
    )
  end

  @spec lit(term()) :: String.t()
  def lit(v) do
    {:ok, json} = Canonical.encode(v)
    json
  end

  defp decl(name, %{"type" => "string"} = s)
       when not is_map_key(s, "enum") and not is_map_key(s, "const"),
       do: "export type #{name} = string & { readonly __brand: '#{name}' };"

  defp decl(name, s), do: "export type #{name} = #{type(s)};"

  defp type(%{"$ref" => name}), do: name
  defp type(%{"oneOf" => bs}), do: Enum.map_join(bs, " | ", &type/1)
  defp type(%{"anyOf" => bs}), do: Enum.map_join(bs, " | ", &type/1)
  defp type(%{"const" => c}), do: lit(c)
  defp type(%{"enum" => e}), do: Enum.map_join(e, " | ", &lit/1)
  defp type(%{"type" => "array", "items" => i}), do: "readonly (#{type(i)})[]"

  defp type(%{"type" => "object", "additionalProperties" => v}) when is_map(v),
    do: "Readonly<Record<string, #{type(v)}>>"

  defp type(%{"type" => "object", "properties" => ps}) when ps == %{}, do: "Record<string, never>"

  defp type(%{"type" => "object", "properties" => ps} = s) do
    required = Map.get(s, "required", [])

    fields =
      Enum.map_join(Enum.sort(ps), "; ", fn {k, sub} ->
        "readonly #{lit(k)}#{if k in required, do: "", else: "?"}: #{type(sub)}"
      end)

    "{ #{fields} }"
  end

  defp type(%{"type" => t}), do: %{"string" => "string", "integer" => "number"}[t] || t
end

# ---- Inputs ----

read = fn rel -> JSON.decode!(File.read!(Path.expand(rel, root))) end
registry = read.(Enum.at(System.argv(), 1, "protocol/capability_registry.json"))
responsibilities = read.("protocol/residency.json")
effects = read.("protocol/effect_registry.json")
pin = &"#{&1["key"]}@#{&1["version"]}"

# ---- ADR-074 trigger ----
# An Elixir host adapter on a portable_capability needs a cross-kernel differential,
# declared and present.
trigger =
  for e <- registry,
      e["residency"] == "portable_capability",
      "elixir" in (e["host_adapters"] || []),
      not File.regular?(Path.join(root, e["differential"] || "")),
      do: "#{pin.(e)}: elixir host adapter without a present differential (ADR-074)"

if trigger != [] do
  Enum.each(trigger, &IO.puts(:stderr, &1))
  System.halt(1)
end

# ---- Residency matrix (05 §6) ----
# The six ResidencyClass values (plus unclassified, a null capability residency), each with
# its capabilities and its non-capability responsibilities (protocol/residency.json).
# Unbound host adapters and fixtures are null, never [].
class = &(&1["residency"] || "unclassified")
bound = &if(&1 == [], do: nil, else: &1)
origins = fn key -> for e <- effects, key in e["allowed_origins"], do: e["type"] end

matrix =
  Map.new(Loka.Core.Contracts.defs()["ResidencyClass"]["enum"] ++ ["unclassified"], fn c ->
    capabilities =
      for e <- registry, class.(e) == c, into: %{} do
        {pin.(e),
         %{
           "portability" => e["portability"],
           "effects" => origins.(e["key"]),
           "host_adapters" => e["host_adapters"],
           "conformance_fixtures" => nil
         }}
      end

    rows =
      for r <- responsibilities,
          r["residency"] == c,
          into: %{},
          do: {r["key"], %{"conformance_fixtures" => bound.(r["fixtures"])}}

    {c, %{"capabilities" => capabilities, "responsibilities" => rows}}
  end)

# ---- docs/contracts.gen.md ----

schema_docs =
  for path <- Enum.sort(Path.wildcard(Path.join(root, "protocol/*.schema.json"))) do
    doc = read.(Path.relative_to(path, root))

    contracts =
      for {name, s} <- Enum.sort(doc["$defs"]) do
        variants =
          for b <- s["oneOf"] || [], {_, %{"const" => v}} <- b["properties"] do
            "  - `#{v}`" <> if(b["description"], do: ": #{b["description"]}", else: "")
          end

        ["- **#{name}**: #{s["description"]}" | variants]
      end

    ["", "## #{doc["title"]} (`protocol/#{Path.basename(path)}`)", "", doc["description"], ""] ++
      contracts
  end

contracts_md =
  Enum.join(
    List.flatten([
      "# Contracts (generated)",
      "",
      "Generated by `elixir bin/contracts.exs` from `protocol/`. Do not edit.",
      "",
      "## Capabilities",
      "",
      "Residency is the declared 05 §6 class, not evidence of an implementation; the",
      "machine-readable matrix is [residency.gen.json](residency.gen.json).",
      "",
      "| Capability | Portability | Residency | Effects |",
      "|---|---|---|---|",
      for(
        e <- registry,
        do:
          "| #{pin.(e)} | #{e["portability"]} | #{class.(e)} | #{Enum.join(origins.(e["key"]), ", ")} |"
      ),
      "",
      "## Other responsibilities (`protocol/residency.json`)",
      "",
      "Foundation contracts that both kernels hold to golden parity, and host and authoring",
      "responsibilities, which are never capabilities (05 §6). No fixtures: none bound yet.",
      "",
      "| Responsibility | Residency | Fixtures |",
      "|---|---|---|",
      for(
        r <- responsibilities,
        do: "| #{r["key"]} | #{r["residency"]} | #{Enum.join(r["fixtures"], ", ")} |"
      ),
      schema_docs,
      ""
    ]),
    "\n"
  )

# ---- Write or check ----

faults =
  for e <- read.("protocol/error_registry.json"),
      e["category"] == "evaluation_fault",
      do: e["code"]

limits = read.("docs/spec/conformance/composition-profile.json")["limits"]

# Owning capability (key@version) of each command, policy op and definition kind, for the
# loader's UNDECLARED_CAPABILITY re-check and command routing (cartridge.schema.json
# DiagnosticCode). Events join when a frozen definition kind references one.
owners =
  for {kind, field} <- [
        {"command", "commands"},
        {"policy", "policies"},
        {"definition", "definitions"}
      ],
      into: %{} do
    {kind, for(e <- registry, name <- e[field] || [], into: %{}, do: {name, pin.(e)})}
  end

# Per capability that owns a command or event: the command and event type names it owns, as
# TypeScript literal unions (never for none). Rule modules are typed by it, so one that
# handles or emits another capability's command or event fails typecheck (kernel/ts/src/world.ts).
owned_union = fn names ->
  if names == [], do: "never", else: Enum.map_join(names, " | ", &Gen.lit/1)
end

owned =
  for e <- registry, (e["commands"] || []) ++ (e["events"] || []) != [] do
    "#{Gen.lit(e["key"])}: { command: #{owned_union.(e["commands"] || [])}; event: #{owned_union.(e["events"] || [])} }"
  end

{:ok, probe} =
  Loka.Core.Canonical.decode(File.read!(Path.join(root, "protocol/fixtures/subset.schema.json")))

targets = %{
  "docs/contracts.gen.md" => contracts_md,
  "docs/residency.gen.json" => Gen.lit(matrix) <> "\n",
  "kernel/ts/src/contracts.gen.ts" =>
    Gen.ts(Loka.Core.Contracts.defs(), "protocol/*.schema.json") <>
      Enum.join(
        [
          "export const EVALUATION_FAULTS: readonly ErrorCode[] = #{Gen.lit(faults)};",
          "export const LIMITS: Readonly<Record<string, number>> = JSON.parse(#{Gen.lit(Gen.lit(limits))});",
          "export const CAPABILITY_OWNERS: Readonly<Record<'command' | 'policy' | 'definition', Readonly<Record<string, string>>>> = JSON.parse(#{Gen.lit(Gen.lit(owners))});",
          "export type Owned = { #{Enum.join(owned, "; ")} };",
          "export const ARTIFACT_MAX_BYTES = #{Loka.Core.Contracts.defs()["ArtifactSize"]["maximum"]};",
          ""
        ],
        "\n"
      ),
  "kernel/ts/test/subset.gen.ts" =>
    Gen.ts(
      Loka.Core.Contracts.Schema.flatten!(%{"subset.schema.json" => probe}),
      "protocol/fixtures/subset.schema.json"
    )
}

case System.argv() do
  [] ->
    for {rel, text} <- targets, do: File.write!(Path.join(root, rel), text)

  ["--check" | _] ->
    stale =
      for {rel, text} <- targets,
          File.read(Path.join(root, rel)) != {:ok, text},
          do: IO.puts(:stderr, "#{rel} is out of date: run elixir bin/contracts.exs")

    if stale != [], do: System.halt(1)
end
