# Generates kernel/ts/src/contracts.gen.ts (TypeScript types plus the flattened schemas) from
# protocol/*.schema.json (spec 04 §12), and kernel/ts/test/subset.gen.ts from the test-only
# probe protocol/fixtures/subset.schema.json. `--check` regenerates in memory and exits 1 if
# a committed file differs. A schema outside the subset fails here as it fails `mix compile`.
#
#   elixir bin/contracts.exs [--check]
root = Path.expand("..", __DIR__)

for f <- ~w(canonical.ex contracts/schema.ex contracts.ex),
    do: Code.require_file(f, Path.join(root, "lib/loka/core"))

defmodule Gen do
  alias Loka.Core.Canonical

  def decl(name, %{"type" => "string"} = s)
      when not is_map_key(s, "enum") and not is_map_key(s, "const"),
      do: "export type #{name} = string & { readonly __brand: '#{name}' };"

  def decl(name, s), do: "export type #{name} = #{type(s)};"

  def type(%{"$ref" => name}), do: name
  def type(%{"oneOf" => bs}), do: Enum.map_join(bs, " | ", &type/1)
  def type(%{"anyOf" => bs}), do: Enum.map_join(bs, " | ", &type/1)
  def type(%{"const" => c}), do: lit(c)
  def type(%{"enum" => e}), do: Enum.map_join(e, " | ", &lit/1)
  def type(%{"type" => "array", "items" => i}), do: "readonly (#{type(i)})[]"

  def type(%{"type" => "object", "additionalProperties" => v}) when is_map(v),
    do: "Readonly<Record<string, #{type(v)}>>"

  def type(%{"type" => "object", "properties" => ps}) when ps == %{}, do: "Record<string, never>"

  def type(%{"type" => "object", "properties" => ps} = s) do
    required = Map.get(s, "required", [])

    fields =
      Enum.map_join(Enum.sort(ps), "; ", fn {k, sub} ->
        "readonly #{lit(k)}#{if k in required, do: "", else: "?"}: #{type(sub)}"
      end)

    "{ #{fields} }"
  end

  def type(%{"type" => t}), do: %{"string" => "string", "integer" => "number"}[t] || t

  def lit(v) do
    {:ok, json} = Canonical.encode(v)
    json
  end
end

# The schemas are embedded as JSON.parse of a JSON string: in an object literal a
# "__proto__" key would set the prototype instead of defining a property.
source = fn defs, from ->
  names = defs |> Map.keys() |> Enum.sort()

  Enum.join(
    List.flatten([
      "// Generated by `elixir bin/contracts.exs` from #{from}. Do not edit.",
      Enum.map(names, &Gen.decl(&1, defs[&1])),
      "",
      "export type Contract = #{Enum.map_join(names, " | ", &Gen.lit/1)};",
      "",
      "export const DEFS: Readonly<Record<Contract, unknown>> = {",
      Enum.map(names, &"  #{Gen.lit(&1)}: JSON.parse(#{Gen.lit(Gen.lit(defs[&1]))}),"),
      "};",
      ""
    ]),
    "\n"
  )
end

{:ok, probe} =
  Loka.Core.Canonical.decode(File.read!(Path.join(root, "protocol/fixtures/subset.schema.json")))

targets = %{
  "kernel/ts/src/contracts.gen.ts" =>
    source.(Loka.Core.Contracts.defs(), "protocol/*.schema.json"),
  "kernel/ts/test/subset.gen.ts" =>
    source.(
      Loka.Core.Contracts.Schema.flatten!(%{"subset.schema.json" => probe}),
      "protocol/fixtures/subset.schema.json"
    )
}

for {rel, text} <- targets do
  case System.argv() do
    [] ->
      File.write!(Path.join(root, rel), text)

    ["--check"] ->
      if File.read(Path.join(root, rel)) != {:ok, text} do
        IO.puts(:stderr, "#{rel} is out of date: run elixir bin/contracts.exs")
        System.halt(1)
      end
  end
end
