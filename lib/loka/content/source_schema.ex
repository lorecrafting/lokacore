# size: allow 350, one generator translates every source contract and shortcut to JSON Schema
defmodule Loka.Content.SourceSchema do
  @moduledoc """
  JSON Schema (draft 2020-12) of each source file kind, for editors and LLM authors
  (docs/system/cartridge.md, Source schema). Built from the contracts the compiler checks source
  with (Source.contracts/0) plus the source shortcuts; `files/0` is what `mix loka.source_schema`
  writes to schemas/source/. Nothing reads these files back: the compiler stays the judge.
  """
  alias Loka.Content.{Compiler, Resources, Source}

  @draft "https://json-schema.org/draft/2020-12/schema"
  @note "Generated by mix loka.source_schema from the compiler's source contracts; do not edit."
  @key %{"$ref" => "Key"}
  @object %{"type" => "object"}
  @prose %{
    "type" => "object",
    "properties" => %{"prose" => %{"type" => "string", "minLength" => 1}},
    "required" => ["prose"],
    "additionalProperties" => false
  }
  @requires ~w(required requiredUnless exactlyOneRequired dependentRequired)
  @maps ~w(properties patternProperties $defs dependentSchemas)
  @lists ~w(anyOf oneOf allOf prefixItems)
  @ones ~w(items additionalProperties not if then else propertyNames contains)
  @roots %{
    "cartridge" => "source.cartridge",
    "facts" => "source.facts",
    "text" => "TextCatalog",
    "resources" => "source.resources",
    "attributes" => "source.attributes",
    "map_positions" => "source.map_positions",
    "areas" => "source.areas"
  }

  @doc "File name => JSON text: defs.schema.json and one `<dir or root file>.schema.json` each."
  @spec files() :: %{String.t() => binary()}
  def files do
    names = Map.merge(@roots, Map.new(Map.keys(Source.dirs()), &{&1, "source." <> &1}))
    kinds = for {file, def} <- names, into: %{}, do: {file <> ".schema.json", top(file, def)}

    Map.put(kinds, "defs.schema.json", %{"$defs" => prune(defs(), Map.values(names))})
    |> Map.new(fn {f, s} -> {f, encode(head(s))} end)
  end

  defp encode(s), do: IO.iodata_to_binary(:json.format(s)) <> "\n"

  defp top(file, def),
    do: %{
      "title" => "Loka cartridge source: #{file}",
      "$ref" => "defs.schema.json#/$defs/" <> def
    }

  defp head(s), do: Map.merge(%{"$schema" => @draft, "$comment" => @note}, s)

  # Every def, translated to standard JSON Schema, refs as #/$defs/<name>.
  defp defs do
    base = Source.contracts() |> Map.update!("TextKey", &prose/1)
    dispatch = for {dir, kind} <- Source.dirs(), into: %{}, do: {"source." <> dir, kind(kind)}

    base
    |> with_partials(members(base))
    |> Map.merge(dispatch)
    |> Map.merge(roots(Source.contracts()))
    |> Map.new(fn {n, s} -> {n, walk(s, &standard/1)} end)
  end

  # Each member and its extends-child form, and the partial defs those reach.
  defp with_partials(base, members) do
    all = Map.merge(base, members)
    changed = changed(all)
    partials = for n <- changed, into: all, do: {"partial." <> n, partial(all[n], changed)}
    for {n, s} <- members, into: partials, do: {"partial." <> n, child(relax(s, changed))}
  end

  # The words of inline prose may stand wherever a text key goes (Loka.Content.Prose).
  defp prose(text_key) do
    {doc, rest} = Map.pop(text_key, "description")
    %{"description" => doc, "anyOf" => [rest, @prose]}
  end

  # A definition file's member, without `key` (it comes from the file stem), with its shortcuts.
  defp members(defs) do
    for {_, _, contract} <- Compiler.kind_contracts(), into: %{} do
      {"source." <> contract, shortcuts(contract, unkey(defs[contract]))}
    end
  end

  # SceneDefinition is a oneOf of whole definitions.
  defp unkey(%{"oneOf" => branches} = s), do: %{s | "oneOf" => Enum.map(branches, &unkey/1)}
  defp unkey(s), do: drop(s, "key")

  defp shortcuts("RoomDefinition", s), do: put(s, "zones", %{"type" => "array", "items" => @key})
  defp shortcuts("NpcDefinition", s), do: put(s, "behaviours", behaviours())
  defp shortcuts("ItemDefinition", s), do: put(s, "behaviours", behaviours())

  defp shortcuts("ReactionRule", s) do
    on = update_in(s, ["properties", "on", "oneOf"], &[signal(&1, "event", "fact_changed") | &1])
    steps = ["properties", "apply", "items", "oneOf"]

    on
    |> update_in(steps, &[signal(&1, "op", "fact.adjust") | &1])
    |> put("zone", @key)
    |> zoned()
  end

  defp shortcuts(_, s), do: s

  # A zone rule names no on.room (Loka.Content.Zones gives each copy its room); others still do.
  defp zoned(s) do
    branches = s["properties"]["on"]["oneOf"]

    roomed =
      for b <- branches,
          "room" in Map.get(b, "required", []),
          do: b["properties"]["event"]["const"]

    s = put_in(s, ["properties", "on", "oneOf"], Enum.map(branches, &unrequire(&1, "room")))

    Map.merge(s, %{
      "if" => %{"type" => "object", "required" => ["zone"]},
      "then" => on_is(%{"properties" => %{"room" => false}}),
      "else" =>
        on_is(%{
          "if" => %{"properties" => %{"event" => %{"enum" => roomed}}},
          "then" => %{"required" => ["room"]}
        })
    })
  end

  defp on_is(s), do: %{"properties" => %{"on" => Map.put(s, "type", "object")}}

  defp behaviours do
    with_args = %{
      "type" => "object",
      "properties" => %{"behaviour" => @key, "with" => @object},
      "required" => ["behaviour"],
      "additionalProperties" => false
    }

    %{"type" => "array", "items" => %{"anyOf" => [@key, with_args]}}
  end

  # The signal step and trigger (Loka.Content.Signals): its target branch with `signal` for `fact`.
  defp signal(branches, tag, target) do
    branch = Enum.find(branches, &(&1["properties"][tag]["const"] == target))
    props = Map.drop(branch["properties"], ["fact", "amount"])
    required = [tag, "signal"]

    %{
      branch
      | "properties" => Map.merge(props, %{tag => %{"const" => "signal"}, "signal" => @key}),
        "required" => required
    }
  end

  defp put(s, name, schema), do: put_in(s, ["properties", name], schema)

  defp drop(s, name),
    do: %{s | "properties" => Map.delete(s["properties"], name)} |> unrequire(name)

  defp unrequire(s, name), do: Map.update(s, "required", [], &(&1 -- [name]))

  # A file in a definition directory: an abstract parent (never checked), an extends child (it
  # may leave out any inherited member), or a whole definition. actions/ holds both kinds.
  defp kind(:behaviour) do
    reactions = %{"type" => "object", "propertyNames" => @key, "additionalProperties" => @object}
    params = %{"type" => "array", "items" => %{"$ref" => "Key", "not" => %{"const" => "holder"}}}

    %{
      "type" => "object",
      "properties" => %{"reactions" => reactions, "params" => params},
      "required" => ["reactions"],
      "additionalProperties" => false
    }
  end

  defp kind(kind) do
    abstract = %{"type" => "object", "properties" => %{"abstract" => %{"const" => true}}}
    child = &Map.put(&1, "$ref", "partial." <> &1["$ref"])

    %{
      "if" => %{"type" => "object", "required" => ["abstract"]},
      "then" => abstract,
      "else" => %{
        "if" => %{"type" => "object", "required" => ["extends"]},
        "then" => child_of(kind, child),
        "else" => whole(kind)
      }
    }
  end

  defp whole(:action) do
    %{
      "if" => %{"type" => "object", "required" => ["command"]},
      "then" => %{"$ref" => "source.ActionDefinition"},
      "else" => %{"$ref" => "source.ActionRecipe"}
    }
  end

  defp whole(kind) do
    {_, _, contract} = List.keyfind(Compiler.kind_contracts(), kind, 1)
    %{"$ref" => "source." <> contract}
  end

  defp child_of(:action, child) do
    w = whole(:action)
    %{w | "then" => child.(w["then"]), "else" => child.(w["else"])}
  end

  defp child_of(kind, child), do: child.(whole(kind))

  # The defs whose extends child differs from the whole one: an object member's requirements
  # drop, recursively through members and maps (Loka.Content.Extends merges objects); list items
  # and alternatives stay whole, since a child's list or scalar replaces the parent's.
  defp changed(defs, ch \\ MapSet.new()) do
    next = for({n, s} <- defs, partial(s, ch) != s, into: MapSet.new(), do: n)
    if next == ch, do: ch, else: changed(defs, next)
  end

  # A child extends one whole member: a member of alternatives (SceneDefinition) relaxes each.
  defp relax(%{"oneOf" => bs} = s, ch), do: %{s | "oneOf" => Enum.map(bs, &partial(&1, ch))}
  defp relax(s, ch), do: partial(s, ch)

  # An extends child names its parent and may give it arguments (Loka.Content.Extends).
  defp child(%{"oneOf" => bs} = s), do: %{s | "oneOf" => Enum.map(bs, &child/1)}
  defp child(s), do: s |> put("extends", @key) |> put("with", @object)

  defp partial(%{} = s, ch) do
    s
    |> Map.drop(@requires ++ ~w(if then else))
    |> Map.new(fn
      {"$ref", r} -> {"$ref", if(r in ch, do: "partial." <> r, else: r)}
      {"properties", ps} -> {"properties", Map.new(ps, fn {n, p} -> {n, partial(p, ch)} end)}
      {"additionalProperties", %{} = p} -> {"additionalProperties", partial(p, ch)}
      other -> other
    end)
  end

  # cartridge.json, facts.json, resources.json, attributes.json and map_positions.json, as the
  # compiler checks them; root files take no shortcut (an area bundle opens into definitions).
  defp roots(defs) do
    fact = defs["FactSpec"] |> drop("key")
    facts = %{"type" => "object", "additionalProperties" => fact}

    bundle =
      for {dir, _} <- Source.dirs(),
          into: %{},
          do:
            {dir,
             %{
               "type" => "object",
               "propertyNames" => @key,
               "additionalProperties" => %{"$ref" => "source." <> dir}
             }}

    %{
      "source.cartridge" => Compiler.manifest_file(defs),
      "source.facts" => put(Compiler.facts_file(), "facts", facts),
      "source.resources" => Resources.file_schema("resources"),
      "source.attributes" => Resources.file_schema("attributes"),
      "source.map_positions" => %{
        "type" => "array",
        "items" => %{"$ref" => "MapPosition"},
        "minItems" => 1
      },
      "source.areas" => %{
        "type" => "object",
        "properties" => bundle,
        "additionalProperties" => false
      }
    }
  end

  # The validator's own keywords as standard ones (Loka.Core.Contracts): oneOf becomes anyOf (the
  # validator picks a branch, it never refuses a second match), examples go, refs get their path.
  defp standard(s) do
    {once, s} = Map.pop(s, "exactlyOneRequired")
    {unless, s} = Map.pop(s, "requiredUnless")

    s =
      Map.new(Map.delete(s, "examples"), fn
        {"oneOf", branches} -> {"anyOf", branches}
        {"$ref", r} -> {"$ref", "#/$defs/" <> r}
        other -> other
      end)

    extra = required_unless(unless) ++ exactly_one(once, unless)
    if extra == [], do: s, else: Map.update(s, "allOf", extra, &(&1 ++ extra))
  end

  defp required_unless(nil), do: []

  defp required_unless(r),
    do: [
      %{
        "anyOf" =>
          for(k <- Map.keys(r), do: %{"required" => [k]}) ++ [%{"required" => hd(Map.values(r))}]
      }
    ]

  defp exactly_one(nil, _), do: []
  defp exactly_one(keys, nil), do: [%{"oneOf" => for(k <- keys, do: %{"required" => [k]})}]

  # Beside requiredUnless the validator checks it only once one of the keys is present.
  defp exactly_one(keys, _),
    do: [%{"not" => %{"anyOf" => for(a <- keys, b <- keys, a < b, do: %{"required" => [a, b]})}}]

  # Applies `f` to every subschema, children first.
  defp walk(%{} = s, f) do
    s |> Map.new(&walk_entry(&1, f)) |> f.()
  end

  defp walk(s, _), do: s

  defp walk_entry({k, %{} = v}, f) when k in @maps,
    do: {k, Map.new(v, fn {n, x} -> {n, walk(x, f)} end)}

  defp walk_entry({k, v}, f) when k in @lists and is_list(v), do: {k, Enum.map(v, &walk(&1, f))}
  defp walk_entry({k, %{} = v}, f) when k in @ones, do: {k, walk(v, f)}
  defp walk_entry(other, _), do: other

  # Only the defs the published files reach.
  defp prune(defs, roots) do
    reach(roots, defs, MapSet.new()) |> then(&Map.take(defs, MapSet.to_list(&1)))
  end

  defp reach([], _, seen), do: seen

  defp reach([n | rest], defs, seen) do
    if n in seen,
      do: reach(rest, defs, seen),
      else: reach(refs(defs[n]) ++ rest, defs, MapSet.put(seen, n))
  end

  defp refs(%{"$ref" => "#/$defs/" <> n} = s), do: [n | refs(Map.delete(s, "$ref"))]
  defp refs(%{} = s), do: Enum.flat_map(Map.values(s), &refs/1)
  defp refs(l) when is_list(l), do: Enum.flat_map(l, &refs/1)
  defp refs(_), do: []
end
